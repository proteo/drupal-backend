<?php

namespace Proteo\DrupalBackend\Contract;

use Proteo\DrupalBackend\Descriptor\ContentType;
use Proteo\DrupalBackend\Descriptor\Descriptor;
use Proteo\DrupalBackend\Descriptor\FieldType;
use Proteo\DrupalBackend\Descriptor\Relation;
use Proteo\DrupalBackend\Descriptor\RelationKind;
use Proteo\DrupalBackend\Descriptor\Source;

/**
 * Renders what the Drupal backend must provide for a descriptor, as a
 * Markdown checklist. Pure function of the descriptor, so the output can be
 * snapshot-tested and diffed when the content model changes.
 */
class ContractGenerator
{
    /**
     * @param  iterable<ContractContributor>  $contributors  Services tagged `drupal-backend.contract`.
     */
    public function __construct(
        private readonly Descriptor $descriptor,
        private readonly iterable $contributors = [],
    ) {}

    public function markdown(): string
    {
        $sections = [
            '# Drupal contract',
            'Generated by `php artisan drupal:contract` for descriptor schema version '.$this->descriptor->schemaVersion.'. Every box is a requirement the backend must meet; `drupal:validate` checks them against a live site.',
            $this->modules(),
            $this->sources(),
            ...array_map(fn (ContentType $type): string => $this->contentType($type), array_values($this->descriptor->contentTypes)),
            ...$this->extraSections(),
            $this->changes(),
        ];

        return implode("\n\n", array_filter($sections))."\n";
    }

    private function modules(): string
    {
        $lines = [
            '## Required modules',
            '',
            '- [ ] JSON:API (core)',
            '- [ ] Decoupled Router (resolves aliases to entities)',
        ];

        foreach ($this->contributors as $contributor) {
            foreach ($contributor->modules() as $module) {
                $lines[] = "- [ ] $module";
            }
        }

        return implode("\n", $lines);
    }

    /**
     * @return list<string>
     */
    private function extraSections(): array
    {
        $sections = [];

        foreach ($this->contributors as $contributor) {
            array_push($sections, ...$contributor->sections());
        }

        return $sections;
    }

    private function sources(): string
    {
        $lines = ['## Sources'];

        foreach ($this->descriptor->sources as $source) {
            $lines[] = '';
            $lines[] = "### `$source->name`";
            $lines[] = '';
            $lines[] = "- [ ] Base URL `$source->baseUrl`, JSON:API at `{$source->jsonapiPath}`";
            $lines[] = '- [ ] Webhook: '.($source->webhookSecret === null
                ? 'no secret configured, so the webhook is inert; set `webhook.secret` to enable it'
                : 'POSTs to `'.$this->webhookUrl($source).'`, signed with the shared secret');
        }

        return implode("\n", $lines);
    }

    private function webhookUrl(Source $source): string
    {
        $path = $this->descriptor->webhook->path.($source->name === $this->descriptor->defaultSource ? '' : '/'.$source->name);

        return rtrim($source->frontendUrl ?? '<frontend URL>', '/').$path;
    }

    private function contentType(ContentType $type): string
    {
        $lines = [
            "## Content type `$type->key`",
            '',
            "- Role: {$type->role->value}, Source `$type->source`",
            "- Resource type `{$type->resourceType()}` at `{$type->resourcePath()}`",
        ];

        if ($type->nativeCollection !== $type->bundle) {
            $lines[] = "- Native collection `$type->nativeCollection`";
        }

        if ($type->fields !== []) {
            $lines[] = '';
            $lines[] = '| Field | Drupal path | Type | Required |';
            $lines[] = '| --- | --- | --- | --- |';
            foreach ($type->fields as $field) {
                $lines[] = "| `$field->name` | `$field->source` | {$this->fieldType($field->type)} | ".($field->required ? 'yes' : 'no').' |';
            }
        }

        if ($type->relations !== []) {
            $lines[] = '';
            $lines[] = '| Relationship | Points to | Cardinality | Include path | Optional |';
            $lines[] = '| --- | --- | --- | --- | --- |';
            foreach ($type->relations as $relation) {
                $lines[] = "| `$relation->via` (as `$relation->name`) | {$this->target($relation)} | ".($relation->many ? 'many' : 'one')." | `{$type->includeOf([$relation->name])}` | ".($relation->optional ? 'yes' : 'no').' |';
            }
        }

        $lines[] = '';
        foreach ($type->includes as $context => $names) {
            $lines[] = "- [ ] `$context` includes `{$type->include($context)}`";
        }

        foreach ($type->conditions as $condition) {
            $lines[] = "- [ ] `$condition->attribute`: present on the resource, condition".($condition->filterable ? ' (filterable)' : '');
        }

        $native = $this->nativeSearch($type);
        if ($native !== []) {
            $lines[] = '';
            $lines[] = 'Native search (the collection must accept these, `drupal:validate` probes each):';
            $lines[] = '';
            array_push($lines, ...$native);
        }

        foreach ($this->contributors as $contributor) {
            $extra = $contributor->forContentType($type);

            if ($extra !== []) {
                $lines[] = '';
                array_push($lines, ...$extra);
            }
        }

        if ($type->sorts !== []) {
            $lines[] = '';
            $lines[] = '- [ ] Sorts accepted upstream: '.implode(', ', array_map(fn (string $sort): string => "`$sort`", array_unique(array_values($type->sorts))));
        }

        return implode("\n", $lines);
    }

    /**
     * @return list<string>
     */
    private function nativeSearch(ContentType $type): array
    {
        if (! $this->descriptor->search->enabled || ! $type->searchable) {
            return [];
        }

        $lines = [];
        $paths = array_keys($type->termFields + $type->relatedTermFields);

        if ($paths !== []) {
            $lines[] = '- [ ] Filterable with `CONTAINS`: '.implode(', ', array_map(fn (string $path): string => "`$path`", $paths));
        }

        $filters = [];

        foreach ($type->filters as $filter) {
            $filters[] = $filter->nativePath;

            foreach ($filter->fields as $field) {
                $filters[] = $field->native;
            }
        }

        $filters = array_values(array_unique(array_filter($filters)));

        if ($filters !== []) {
            $lines[] = '- [ ] Filterable by: '.implode(', ', array_map(fn (string $path): string => "`$path`", $filters));
        }

        return $lines;
    }

    private function fieldType(FieldType $type): string
    {
        return match ($type) {
            FieldType::Html => 'text (formatted, with `value`)',
            FieldType::Date => 'date (ISO 8601)',
            FieldType::Excerpt => 'text (plain, shortened here)',
            FieldType::Integer => 'integer',
            FieldType::Boolean => 'boolean',
            FieldType::String => 'string',
        };
    }

    private function target(Relation $relation): string
    {
        return match ($relation->kind) {
            RelationKind::Content => "content type `$relation->to`",
            RelationKind::File => 'file entity in `'.$relation->via.'` with `uri`, `filename`, `filemime`, `filesize`',
            RelationKind::Image => 'media image (file in `'.($relation->imageField ?? 'field_media_image').'`)',
        };
    }

    private function changes(): string
    {
        $entityTypes = [];
        foreach ($this->descriptor->contentTypes as $type) {
            $entityTypes[$type->entityType] = true;

            foreach ($type->relations as $relation) {
                if ($relation->kind === RelationKind::Image) {
                    $entityTypes['media'] = $entityTypes['file'] = true;
                } elseif ($relation->kind === RelationKind::File) {
                    $entityTypes['file'] = true;
                }
            }
        }

        ksort($entityTypes);
        $hooks = implode(', ', array_map(fn (string $entityType): string => "`$entityType`", array_keys($entityTypes)));

        $lines = [
            '## Drupal changes',
            '',
            "- [ ] Implement `hook_ENTITY_TYPE_insert`, `_update` and `_delete` for every entity type the frontend renders: $hooks. Edits to a type without a hook never clear the cache.",
        ];

        $lines[] = '- [ ] Payload v2: `{"changes": [{"event": "<entity_type>.<insert|update|delete>", "entity_type", "bundle", "uuid", "nonce"}]}`; the frontend ignores the content, but the nonce prevents replay.';
        $lines[] = '- [ ] Accumulate the changes of the request into that one `changes` list and send it once from `destruct()`, after the transaction commits.';
        $lines[] = '- [ ] Settings `cache_webhook.url` and `cache_webhook.secret` (per Source, see above).';
        $lines[] = '- [ ] Headers `X-Drupal-Timestamp` and `X-Drupal-Signature`, the HMAC-SHA256 of `{timestamp}.{body}` over the exact body bytes sent.';
        $lines[] = '- [ ] The hook service is tagged `needs_destruction` and implements `DestructableInterface`.';
        $lines[] = '';
        $lines[] = 'Reference snippet:';
        $lines[] = '';
        $lines[] = '```php';
        $lines[] = trim(self::SNIPPET);
        $lines[] = '```';

        return implode("\n", $lines);
    }

    private const string SNIPPET = <<<'PHP'
protected array $changes = [];

protected function scheduleFrontendFlush(EntityInterface $entity, string $operation): void {
  $this->changes[] = [
    'event' => $entity->getEntityTypeId() . '.' . $operation,
    'entity_type' => $entity->getEntityTypeId(),
    'bundle' => $entity->bundle(),
    'uuid' => $entity->uuid(),
    'nonce' => Crypt::randomBytesBase64(16),
  ];
}

public function destruct(): void {
  if (!$this->changes) {
    return;
  }
  $body = Json::encode(['changes' => $this->changes]);
  $this->changes = [];
  $secret = (string) Settings::get('cache_webhook.secret', FALSE);
  $url = Settings::get('cache_webhook.url', FALSE);
  if (!$secret || !$url) {
    return;
  }
  $timestamp = (string) $this->time->getCurrentTime();
  try {
    $this->httpClient->request('POST', $url, [
      // Must be the exact bytes that were signed.
      'body' => $body,
      'headers' => [
        'Content-Type' => 'application/json',
        'X-Drupal-Timestamp' => $timestamp,
        'X-Drupal-Signature' => hash_hmac('sha256', $timestamp . '.' . $body, $secret),
      ],
      'timeout' => 5,
    ]);
  }
  catch (\Throwable $e) {
    // Never break content editing because the frontend is unreachable.
    $this->logger->error('Frontend cache flush failed: @message', ['@message' => $e->getMessage()]);
  }
}
PHP;
}
